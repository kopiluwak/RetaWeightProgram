/**
 * Neutron voice-log: bundled on-device food database.
 *
 * Curated common-foods dataset (~350 foods + ~700 aliases ≈ 1,000 searchable
 * names) covering what people actually dictate: protein sources, dairy,
 * grains, produce, fast food, snacks, shakes. Values are APPROXIMATE protein
 * per 100 g as eaten (cooked where applicable) — good enough for tracking,
 * not lab-precise (per spec). The AI fallback (/nutrition/parse) covers the
 * long tail, so breadth beats precision here.
 *
 * Pure data + pure TS — no React Native imports (unit-testable under node).
 *
 * Row format (compact tuples to keep the bundle small):
 *   [name, aliases, proteinPer100g, defaultServingG, servingLabel, category]
 * defaultServingG = grams logged when the user gives no quantity, and the
 * weight of ONE unit for countable foods ("2 eggs" -> 2 * 50 g).
 */

